plt.axhline(cum_var[9], color='#e63946', linestyle='--', label=f'10 Components: {cum_var[9]:.1f}% Variance')
plt.title('Figure 2: Cumulative Explained Variance by Principal Components', fontsize=12, fontweight='bold', pad=10)
